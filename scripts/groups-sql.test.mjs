import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
const { PGlite } = await import(process.env.PGLITE_PATH ? pathToFileURL(process.env.PGLITE_PATH).href : "@electric-sql/pglite");
const db = new PGlite();
const ids = Array.from({ length: 5 }, (_, i) => `00000000-0000-4000-8000-00000000000${i + 1}`);
const [teacherA, teacherB, admin, studentA, studentB] = ids;
try {
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth;
    create table auth.users(id uuid primary key, email text, raw_user_meta_data jsonb default '{}', created_at timestamptz default now(), is_anonymous boolean default false);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create table public.profiles(id uuid primary key references auth.users(id), full_name text, email text, created_at timestamptz default now());
    alter table profiles enable row level security;
    create policy own_profile on profiles for all to authenticated using(id=auth.uid()) with check(id=auth.uid());
    grant usage on schema public, auth to authenticated, anon, service_role;
    grant select, insert, update on profiles to authenticated;
    create table practice_answers(user_id uuid, score int);
    alter table practice_answers enable row level security;
    create policy own_result on practice_answers for select to authenticated using(user_id=auth.uid());
    grant select on practice_answers to authenticated;
  `);
  await db.exec(await readFile(new URL("../supabase/migrations/add_roles.sql", import.meta.url), "utf8"));
  for (const [i, id] of ids.entries()) {
    await db.query("insert into auth.users(id,email,raw_user_meta_data) values($1,$2,$3)", [id, `fixture-${i}@example.com`, JSON.stringify({ avatar_url: "https://example.com/avatar.png" })]);
    await db.query("insert into profiles(id,full_name,role) values($1,$2,$3)", [id, `User ${i}`, i < 2 ? "teacher" : i === 2 ? "admin" : "student"]);
  }
  await db.query("insert into practice_answers values($1,100)", [studentA]);
  const migration = await readFile(new URL("../supabase/migrations/add_groups.sql", import.meta.url), "utf8");
  await db.exec(migration);
  await db.exec(migration);
  const asUser = async (id) => {
    await db.exec("reset role; set role authenticated");
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
  };
  const create = async (name) => (await db.query("select create_group($1) as id", [name])).rows[0].id;
  const join = async (code) => (await db.query("select join_group_by_code($1) as id", [code])).rows[0].id;
  await asUser(teacherA);
  const a = await create("Class A");
  const aCode = (await db.query("select join_code from groups where id=$1", [a])).rows[0].join_code;
  assert.match(aCode, /^[ABCDEFGHJKMNPQRSTUVWXYZ23456789]{8}$/);
  await asUser(teacherB);
  const b = await create("Class B");
  const bCode = (await db.query("select join_code from groups where id=$1", [b])).rows[0].join_code;
  assert.equal((await db.query("select * from groups where id=$1", [a])).rows.length, 0);
  assert.equal((await db.query("select * from list_my_groups()")).rows.length, 1);
  await assert.rejects(db.query("select * from get_group_members($1)", [a]), /Group unavailable/);
  await asUser(studentA);
  assert.equal((await db.query("select * from groups")).rows.length, 0);
  await assert.rejects(db.query("insert into group_members(group_id,student_id) values($1,$2)", [a, studentA]), /permission denied/);
  await db.exec("reset role; grant insert on group_members to authenticated; set role authenticated");
  await assert.rejects(db.query("insert into group_members(group_id,student_id) values($1,$2)", [a, studentA]), /row-level security/);
  await db.exec("reset role; revoke insert on group_members from authenticated; set role authenticated");
  await assert.rejects(create("Illegal class"), /Staff required/);
  await assert.rejects(join("ZZZZZZZZ"), /Invalid or archived/);
  assert.equal(await join(` ${aCode.toLowerCase()} `), a);
  assert.equal(await join(aCode), a);
  const firstJoined = (await db.query("select joined_at from group_members where group_id=$1", [a])).rows[0].joined_at;
  assert.equal((await db.query("select * from group_members")).rows.length, 1);
  assert.equal((await db.query("select * from groups where id=$1", [b])).rows.length, 0);
  const summary = (await db.query("select * from list_my_groups()")).rows[0];
  assert.equal(summary.teacher_name, "User 0");
  assert.equal(Number(summary.member_count), 1);
  assert.equal((await db.query("select * from profiles where id=$1", [teacherA])).rows.length, 0);
  await assert.rejects(db.query("select * from get_group_members($1)", [a]), /Group unavailable/);
  await asUser(studentB);
  await join(bCode);
  await asUser(teacherA);
  assert.equal((await db.query("select * from profiles where id=$1", [studentA])).rows.length, 0);
  assert.equal((await db.query("select * from practice_answers where user_id=$1", [studentA])).rows.length, 0);
  const roster = (await db.query("select * from get_group_members($1)", [a])).rows;
  assert.equal(roster.length, 1);
  assert.deepEqual(Object.keys(roster[0]).sort(), ["avatar_url", "full_name", "joined_at", "student_id"]);
  assert.equal(roster[0].full_name, "User 3");
  assert.equal((await db.query("delete from group_members where group_id=$1 returning *", [b])).rows.length, 0);
  await assert.rejects(db.query("update groups set teacher_id=$1 where id=$2", [teacherB, a]), /row-level security/);
  await assert.rejects(db.query("update groups set join_code='ABCDEFGH' where id=$1", [a]), /permission denied/);
  const rotated = (await db.query("select rotate_group_code($1) as code", [a])).rows[0].code;
  assert.notEqual(rotated, aCode);
  await asUser(studentA);
  await assert.rejects(join(aCode), /Invalid or archived/);
  await join(rotated);
  assert.equal((await db.query("select joined_at from group_members where group_id=$1", [a])).rows[0].joined_at.getTime(), firstJoined.getTime());
  await asUser(teacherA);
  await db.query("update groups set name='Renamed', archived=true where id=$1", [a]);
  await asUser(studentA);
  await assert.rejects(join(rotated), /Invalid or archived/);
  assert.equal((await db.query("select archived from groups where id=$1", [a])).rows[0].archived, true);
  await asUser(admin);
  assert.equal((await db.query("select * from list_my_groups()")).rows.length, 2);
  assert.equal((await db.query("select * from list_group_teachers()")).rows.length, 3);
  await assert.rejects(db.query("update groups set teacher_id=$1 where id=$2", [studentA, a]), /must be staff/);
  await db.query("update groups set teacher_id=$1 where id=$2", [teacherB, a]);
  await asUser(teacherA);
  assert.equal((await db.query("select * from groups")).rows.length, 0);
  await asUser(teacherB);
  assert.equal((await db.query("select * from groups")).rows.length, 2);
  await db.query("delete from group_members where group_id=$1 and student_id=$2", [a, studentA]);
  await asUser(studentA);
  assert.equal((await db.query("select * from groups")).rows.length, 0);
  await db.exec("reset role; set role service_role");
  assert.equal((await db.query("select * from groups")).rows.length, 2);
  assert.equal((await db.query("select * from group_members")).rows.length, 1);
  for (const table of ["groups", "group_members"]) for (const privilege of ["SELECT", "INSERT", "UPDATE", "DELETE"]) {
    assert.equal((await db.query("select has_table_privilege('service_role', $1, $2) as allowed", [table, privilege])).rows[0].allowed, true);
  }
  await db.exec("reset role; set role anon");
  await assert.rejects(db.query("select * from groups"), /permission denied/);
  await assert.rejects(join(bCode), /permission denied/);
  await db.exec("reset role");
  await db.exec(migration);
  assert.equal(Number((await db.query("select count(*) as total from groups")).rows[0].total), 2);
  console.log("Groups SQL tests passed (RLS isolation, invitation join, duplicate prevention, code rotation, archive, removal, transfers, grants and no result exposure)");
} finally { await db.close(); }
