import assert from "node:assert/strict";
import { analyzeAssignment, reportCsv, reportStatus, elapsedSeconds, type ReportRow } from "../lib/assignmentReport.ts";
import { HomeworkClock } from "../lib/homeworkClock.ts";
const due = "2026-11-14T12:00:00Z";
const row = (id: string, status: ReportRow["status"] = "submitted"): ReportRow => ({ student_id: id, full_name: id, is_member: true, submission_id: id, attempt_no: 1, status, started_at: "2026-11-14T11:00:00Z", submitted_at: status === "submitted" ? due : null, correct_count: 1, total_count: 2, extra_attempts: 0 });
const rows = [row("s1"), { ...row("s2"), submitted_at: "2026-11-14T12:00:01Z", correct_count: 0 }, row("s3", null), row("s4", "in_progress")];
const answer = (sid: string, correct: boolean, text: string) => ({ submission_id: sid, question_id: "q1", is_correct: correct, answer: text, answered_at: due, time_spent_seconds: 10 });
const report = analyzeAssignment(rows, [answer("s1", false, "B"), answer("s2", false, "B"), answer("old-attempt", true, "A"), answer("s4", true, "A")], [{ question_id: "q1", position: 1 }, { question_id: "q2", position: 2 }], due);
assert.deepEqual(report.summary, { total: 4, submitted: 2, late: 1, notStarted: 1, average: 25 });
assert.equal(report.questions[0].frequentWrong, "B");
assert.equal(report.questions[0].frequentWrongCount, 2);
assert.equal(report.questions[0].needsReview, true);
assert.equal(report.questions[1].unanswered, 2);
assert.equal(report.questions[1].needsReview, true);
const half = analyzeAssignment(rows, [answer("s1", true, "A")], [{ question_id: "q1", position: 1 }], due);
assert.equal(half.questions[0].needsReview, false, "Exactly 50% mistakes is not more than half");
assert.equal(analyzeAssignment([], [], [{ question_id: "q1", position: 1 }], due).summary.average, null);
assert.equal(reportStatus(rows[0], due), "submitted");
assert.equal(reportStatus(rows[1], due), "late");
assert.equal(reportStatus(rows[2], due), "not_started");
assert.equal(elapsedSeconds(rows[0]), 3600);
const csv = reportCsv([{ ...rows[0], full_name: '=HYPERLINK("bad")' }, { ...rows[1], full_name: 'Алия, "ученица"\nA' }], due);
assert.ok(csv.startsWith("\uFEFF")); assert.ok(csv.includes("'=HYPERLINK")); assert.ok(csv.includes('""ученица""'));
let now = 0;
const clock = new HomeworkClock({ q1: 7 }, () => now);
clock.enter("q1"); now = 2500; clock.capture(); assert.equal(clock.seconds("q1"), 9);
clock.pause(); now = 10000; assert.equal(clock.seconds("q1"), 9);
clock.resume(); now = 11500; clock.pause(); assert.equal(clock.seconds("q1"), 11);
clock.enter("q2", false); now = 20000; clock.capture(); assert.equal(clock.seconds("q2"), 0);
console.log("Assignment report tests passed (latest-attempt analytics, skips, late boundary, CSV escaping and visible question time)");
