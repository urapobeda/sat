assert.equal(reason(source,'A','D'),'It reverses the relationship.');
assert.equal(reason(source,'B','D'),'This choice is incorrect because it ignores the final sentence.');
assert.equal(reason(source,'C','D'),'The text does not support it.');
assert.equal(reason(source,'D','D'),null);
assert.equal(reason(source,'0.5',null),null);
assert.equal(reason('Choices A, B, and C are incorrect. These values omit the constant. Choice D is correct. Full solution.','B','D'),'These values omit the constant.');
assert.equal(reason('Choice A is incorrect. The correct answer is D.','A','D'),null);
assert.equal(reason('Choice A is incorrect. Use choice D instead.','A','D'),null);
assert.equal(reason('Choice A is incorrect. [[img:0]]','A','D'),null);
assert.equal(reason('No separate choice explanations.','A','D'),null);
