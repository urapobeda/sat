import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import ts from 'typescript';
const require=createRequire(import.meta.url),root=fileURLToPath(new URL('../',import.meta.url)),cache=new Map();
function load(relative){
  const base=path.join(root,relative),filename=[base,base+'.ts',base+'.tsx'].find(p=>fs.existsSync(p)&&fs.statSync(p).isFile());
  if(cache.has(filename))return cache.get(filename).exports;
  const compiledModule={exports:{}};cache.set(filename,compiledModule);
  const code=ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,jsx:ts.JsxEmit.ReactJSX,esModuleInterop:true}}).outputText;
  new Function('require','module','exports',code)(name=>name.startsWith('@/')?load(name.slice(2)):require(name),compiledModule,compiledModule.exports);
  return compiledModule.exports;
}
