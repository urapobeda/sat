import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "typescript";
const source = await readFile(new URL("../lib/vocabulary.ts", import.meta.url), "utf8");
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const v = await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
assert.equal(v.selectedVocabularyWord(" “Running,” "), "Running");
for (const bad of ["two words", "123", "", "<script>", "a\nb"]) assert.equal(v.selectedVocabularyWord(bad), null);
assert.equal(v.selectedVocabularyWord("well-known"), "well-known");
const words = ["run", "make", "study", "box", "paint", "stop", "agree"].map(word => ({ word, id: word }));
const index = v.vocabularyIndex(words);
for (const [inflected, expected] of [["runs", "run"], ["running", "run"], ["making", "make"], ["studies", "study"], ["studied", "study"], ["boxes", "box"], ["paintings", "paint"], ["stopped", "stop"], ["agreed", "agree"]]) assert.equal(v.lookupVocabulary(index, inflected)[0]?.word, expected, inflected);
assert.equal(v.lookupVocabulary(v.vocabularyIndex([...words, { word: "running", id: "exact" }]), "running")[0].id, "exact");
assert.equal(v.lookupVocabulary(index, "unknown").length, 0);
assert.equal(v.parseVocabularyImport("infer — translation — A definition\n\n derive - meaning - Another definition").length, 2);
assert.throws(() => v.parseVocabularyImport("infer — translation — def\nINFER — translation — def"), /repeated/);
assert.throws(() => v.parseVocabularyImport("invalid line"), /Line 1/);
assert.throws(() => v.parseVocabularyImport(""), /1 and 500/);
let reads = 0;
const loader = v.createVocabularyPageLoader(async () => { reads++; return words; });
await Promise.all([loader.load(), loader.load(), loader.load()]); await loader.load(); assert.equal(reads, 1);
loader.retry(); await loader.load(); assert.equal(reads, 2);
const position = v.vocabularyPosition({ top: 10, bottom: 30, left: 0, right: 20 }, 336, 200, 360, 640);
assert.deepEqual(position, { left: 12, top: 40 });
assert.equal(v.vocabularyPosition({ top: 400, bottom: 430, left: 900, right: 950 }, 340, 200, 1024, 768).top, 190);
console.log("Vocabulary logic tests passed: selection, inflections, exact priority, imports, one-load cache and popup bounds.");
